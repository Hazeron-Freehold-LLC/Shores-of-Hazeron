QString AuDice::RandomWord()
{
	// Determine how many syllables in the word.
	const char* wordStruct = 0;
	int syllables = 0;
	int sylroll = Roll(1,100,-1);	// 0-99 percent
	if(sylroll < 15)
	{
		// Four syllables
		syllables = 4;
		wordStruct = s_WordStructure4[Roll(1,s_WordStructure4Count,-1)];
	}
	else if(sylroll < 50)
	{
		// Two syllables
		syllables = 2;
		wordStruct = s_WordStructure2[Roll(1,s_WordStructure2Count,-1)];
	}
	else
	{
		// Three syllables
		syllables = 3;
		wordStruct = s_WordStructure3[Roll(1,s_WordStructure3Count,-1)];
	}

	QString word;	// This will be our return value.
	for(int sy=0; sy<syllables; sy++)
	{
		char table = wordStruct[sy];
		const char *syllable;
		switch(table)
		{
			case 'c':
				syllable = s_SyllableCV[Roll(1,s_SyllableCVCount,-1)];
				break;
			case 'v':
				syllable = s_SyllableVC[Roll(1,s_SyllableVCCount,-1)];
				break;
			case 'C':
				syllable = s_SyllableCVC[Roll(1,s_SyllableCVCCount,-1)];
				break;
			default:
				syllable = 0;
				break;
		}
		if(syllable)
			word += syllable;
	}
	return word;
}

QString AuDice::RandomCityName()
{
	// Start with a random word.
	QString cityname(RandomWord());

	// Roll 0-99 percent for probability of prefix and/or suffix.
	int ps = Roll(1,100,-1);
	if(ps < 5)
	{
		// 5 percent probability of a prefix and a suffix.
		QString prefix = s_CityNamePrefix[Roll(1,s_CityNamePrefixCount,-1)];
		QString suffix = s_CityNameSuffix[Roll(1,s_CityNameSuffixCount,-1)];
		if(prefix[prefix.length()-1] == ' ')
			cityname[0] = cityname[0].toUpper();
		cityname = prefix + cityname + suffix;
	}
	else if(ps < 15)
	{
		// 10 percent probability of a prefix.
		QString prefix = s_CityNamePrefix[Roll(1,s_CityNamePrefixCount,-1)];
		if(prefix[prefix.length()-1] == ' ')
			cityname[0] = cityname[0].toUpper();
		cityname = prefix + cityname;
	}
	else if(ps < 30)
	{
		// 15 percent probability of a suffix.
		QString suffix = s_CityNameSuffix[Roll(1,s_CityNameSuffixCount,-1)];
		cityname[0] = cityname[0].toUpper();
		cityname += suffix;
	}
	else
	{
		cityname[0] = cityname[0].toUpper();
	}
	return cityname;
}

