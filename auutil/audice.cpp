QString AuDice::RandomPassword(int length)
{
	Q_ASSERT(length > 0);				// Reject illogical negative and zero-length password requests.
	Q_ASSERT(length < 100);				// Keep the length somewhat sane.
	QString password;
	QString passChars("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789");
	for(int chr=0; chr<length; chr++)
	{
		int randChr = Roll(1, passChars.length(), -1);
		password += passChars[randChr];
	}
	return password;
}

quint16 AuDice::RandomLogValue(quint16 value, quint16 maxPossibleValue)
{
	// Range of return values is based on a logarithmic progression in size away from the current size, lower and higher.
	quint8 logByte = ToLogByte(value, maxPossibleValue);

	// The lowest possible random value is the value of the next lowest log byte.
	quint16 valueMin;
	if(logByte)
	{
		valueMin = FromLogByteD(logByte - .5, maxPossibleValue);	// 1/2 way to the next log byte value lower.
		if(valueMin < 0xffff)
			valueMin++;
		if(valueMin > value)
			valueMin = value;
	}
	else
		valueMin = 0;											// We are already at the bottom of the range.

	// The highest possible random value is the value of the next highest log byte.
	quint16 valueMax;
	if(logByte < d_LogByteRange)
	{
		valueMax = FromLogByteD(logByte + .5, maxPossibleValue);	// 1/2 way to the next log byte value higher.
		if(valueMax)
			valueMax--;
		if(valueMax < value)
			valueMax = value;
	}
	else
		valueMax = maxPossibleValue;							// We are already at the top of the range.

	// Randomly generate a value within the range.
	int valueRange = valueMax - valueMin + 1;
	if(valueRange < 2)
		return value;					// Range is too tight to generate a value.
	int d = valueRange/2 + 1;			// Dice sides
	int r = Roll(2, d, -2);				// Roll them bones. Result will be 0 to d*2-2, inclusive.
	int v = valueMin + r;				// Value in the range, could exceed the range by 1 at this point.
	if(v > valueMax)
		return valueMax;				// Caught that range exceeded case.
	return v;
}

quint8 AuDice::RandomQuality()
{
	int r;
	do
	{
		double mean = 128.;					// (1 + 255)/2;			// Average Q is 128.
		double standardDeviation = 127./3.;	// (255. - mean)/3.;	// This puts Q1 and Q255 at 3 sigma.
		r = (int)round(RandomGaussianDistribution(mean, standardDeviation));
	}
	while(r < 1 || r >= 256);
	return (quint8)r;
}

// Derived from: https://phoxis.org/2013/05/04/generating-random-numbers-from-normal-distribution-in-c/
double AuDice::RandomGaussianDistribution(double mean, double standardDeviation)
{
	double U1, U2, W;
	do
	{
		U1 = -1 + ((double)Random() / (double)0xffffffff) * 2;	// -1 to 1
		U2 = -1 + ((double)Random() / (double)0xffffffff) * 2;	// -1 to 1
		W = pow(U1, 2) + pow(U2, 2);
	}
	while(W >= 1 || W == 0);
	double mult = sqrt((-2 * log(W)) / W);
	double X1 = U1 * mult;
	return mean + standardDeviation * X1;
}

