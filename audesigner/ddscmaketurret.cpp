DdScMakeTurret::DdScMakeTurret(AuDesignerView* view) : DdCommand(view)
{
}

QString DdScMakeTurret::WikiTopic() const
{
	return "Designer_Menu#Turret";
}

void DdScMakeTurret::UpdatePrompt() const
{
	QString prompt;

	prompt = QObject::tr("<html>"
			"<span style=\"color: %2;\">Turret pivot location. "
			"</span>"
			"<span style=\"color: rgb(255, 255, 0);\">?%1Help, </span>"
			"<span style=\"color: rgb(255, 255, 0);\">Esc%1Stop. </span>"
			"</html>")
		.arg('=')
		.arg(m_pWnd->palette().color(QPalette::WindowText).name());

	m_pWnd->CommandPromptChanged(prompt);
}

AuPoint DdScMakeTurret::CoordinateEntered(const AuPoint& loc, bool fromKeyboard, int keymods)
{
	Q_UNUSED(fromKeyboard);
	Q_UNUSED(keymods);

	if(MakeIt(loc))
		Terminate();

	return loc;
}

void DdScMakeTurret::RenderCursor(const AuMatrix4x4& projection, const AuMatrix4x4& model, DaPerson* sceneAtom,
		const QPoint& pxCursor, AuGLEffects& re, QOpenGLWidget* glw, bool snappedToExistingShape)
{
	const DaDesigner* pde = sceneAtom->FindParentDesignerInEnv();
	if(!pde)
		return;

	// Get cursor location in coordinates relative to the design environment.
	AuPoint loc = m_pWnd->FromPixelToDesignPlane(sceneAtom, pxCursor, true, 0);

	// Cursor lines must be relative to scene atom.
	AuMatrix4x4 ts;
	sceneAtom->GetTransformRelativeToParent(ts, pde);
	ts = ts.Inverse();

	AuMatrix4x4 pmv = projection * model * ts;

	// Draw the blip in pixel space.
	DrawBlip(pmv, loc, m_pWnd->DesignPlane(), re, glw, snappedToExistingShape);
}

bool DdScMakeTurret::OnKeyDown(QKeyEvent* e)
{
	// Pass it down so the coordinate input bar gets first crack at it. The only letters it consumes are A, P and R.
	if(DdCommand::OnKeyDown(e))
		return true;

	return false;
}

bool DdScMakeTurret::MakeIt(const AuPoint& basePivot)
{
	AuPoint baseAxis = m_pWnd->DesignPlane().ProjectVector(0,0,1);

	auApp->DesignerMakeTurret(m_pWnd->DesignerPartSelection(), basePivot, baseAxis);

	return true;
}
